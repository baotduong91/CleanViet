import re
import unicodedata


def normalize(value):
    value = unicodedata.normalize("NFD", value.lower().replace("đ", "d"))
    return re.sub(
        r"[^a-z0-9 ]+", " ", "".join(c for c in value if not unicodedata.combining(c))
    ).strip()


